"""Plot saved A/B free-energy gaps and their absolute errors.

Delta G/kBT = log(P_A/P_B), using integrated angular basin populations.
Only rows with both A and B above the saved threshold in both ensembles qualify.
ABC targets are included. No model samples are generated by this script.
"""

import csv
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np


RESULTS_ROOT = Path("results")
OUTPUT_DIR = RESULTS_ROOT / "plots"


def plot_delta_g(results_paths, output_dir=OUTPUT_DIR):
    groups = {}
    excluded = 0
    thresholds = set()
    for path in results_paths:
        with Path(path).open(newline="") as handle:
            for row in csv.DictReader(handle):
                label = f"{row['loss_dim']}D / {row['loss_type'].upper()}"
                groups.setdefault(label, [])
                thresholds.add((float(row["active_basin_threshold"]), float(row["basin_half_width"])))
                if row["both_basins_present"].lower() != "true":
                    excluded += 1
                    continue
                target, generated, error = (float(row[key]) for key in
                    ("deltaG_target_kBT", "deltaG_optimized_kBT", "abs_deltaG_error_kBT"))
                if not np.isfinite((target, generated, error)).all() or not np.isclose(error, abs(generated - target)):
                    raise ValueError(f"{path}: inconsistent or nonfinite A/B free energies")
                groups[label].append((target, generated, error))
    if not groups:
        raise ValueError("No recovery rows found")
    if len(thresholds) != 1:
        raise ValueError("Compare runs with the same basin sizes and presence threshold")
    groups = {label: np.asarray(values).reshape(-1, 3) for label, values in sorted(groups.items())}
    pooled = np.concatenate(list(groups.values()))
    fig, axes = plt.subplots(1, 2, figsize=(11, 5), layout="constrained")
    if len(pooled):
        bins = np.histogram_bin_edges(pooled[:, 2], bins="fd", range=(0, pooled[:, 2].max() or 1))
        for (label, values), color in zip(groups.items(), plt.rcParams["axes.prop_cycle"].by_key()["color"]):
            axes[0].scatter(values[:, 0], values[:, 1], s=25, alpha=0.7, color=color,
                            label=f"{label} (n={len(values)})")
            if len(values):
                axes[1].hist(values[:, 2], bins=bins, weights=np.full(len(values), 1 / len(values)),
                             histtype="step", linewidth=1.8, color=color, label=label)
        lo, hi = pooled[:, :2].min(), pooled[:, :2].max()
        pad = 0.05 * max(hi - lo, 1)
        axes[0].plot([lo - pad, hi + pad], [lo - pad, hi + pad], "k--", linewidth=1)
        for ax in axes:
            ax.legend(frameon=False)
    else:
        for ax in axes:
            ax.text(0.5, 0.5, "No runs with A and B present in both ensembles",
                    ha="center", transform=ax.transAxes, fontsize=10)
    axes[0].set(xlabel=r"Target $\Delta G/k_BT$", ylabel=r"Generated $\Delta G/k_BT$")
    axes[1].set(xlabel=r"$|\Delta G_{generated}-\Delta G_{target}|/k_BT$", ylabel="Probability per bin")
    for ax in axes:
        ax.spines[["top", "right"]].set_visible(False)
        ax.grid(color="0.9")
    threshold, _ = next(iter(thresholds))
    fig.supxlabel(f"A/B basin populations > {threshold:.0%} in both ensembles; "
                  f"{excluded} runs excluded; all other available runs shown", fontsize=9)
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    path = output_dir / "delta_g.png"
    fig.savefig(path, dpi=300)
    plt.close(fig)
    print(f"Saved {path}: {len(pooled)} A/B comparisons; {excluded} excluded")
    return path


if __name__ == "__main__":
    plot_delta_g(sorted(RESULTS_ROOT.glob("*d_*/recovery.csv")))
